/// Справка хозяйства: то, что человек спрашивает, застряв на экране.
///
/// Лежит в коде, а не на сервере, по двум причинам. Первая — связь: фермер открывает помощь в
/// цеху или в степи, то есть ровно там, где интернета нет, и там же чаще всего застревает.
/// Вторая — правда: текст описывает кнопки, и если кнопку переименовали, статья должна поехать
/// тем же коммитом, а не остаться висеть в базе от прошлой версии приложения.
///
/// Тексты повторяют инструкцию, написанную для первых хозяйств, — но короче: её читают с
/// телефона, стоя, одной рукой.
