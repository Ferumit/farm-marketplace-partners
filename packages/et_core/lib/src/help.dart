/// Приводим к одному виду то, что человек набирает, и то, по чему ищем.
///
/// «ё» здесь не придирка: слово «счёт» почти никто не набирает через «ё» — на казахстанской
/// раскладке её ещё надо найти. Без этой замены самый частый вопрос фермера («где счёт») не
/// находит статью про счёт, и поиск выглядит сломанным.
String _norm(String s) => s.toLowerCase().replaceAll('ё', 'е').replaceAll('й', 'и');

/// Слова, которыми спрашивают, а не называют. Сами по себе они ничего не ищут: «где чек» — это
/// запрос про чек, а «где» лишь мешает.
const _askWords = {'где', 'как', 'что', 'куда', 'когда', 'почему', 'зачем', 'чем', 'мне', 'мой', 'моя'};

/// Сколько букв у двух слов общего начала.
///
/// Нужно из-за русского: «закрыть» и «закрывается», «смену» и «смена» — для спрашивающего одно
/// слово, но подстрокой друг в друге они не лежат. Полноценная морфология тут излишня, статей
/// десяток; общего начала достаточно.
int _sharedStart(String a, String b) {
  final n = a.length < b.length ? a.length : b.length;
  var i = 0;
  while (i < n && a.codeUnitAt(i) == b.codeUnitAt(i)) {
    i++;
  }
  return i;
}

/// Поиск по словам. Ищем по заголовку, ответу, шагам и тегам: человек набирает «куда платят»
/// или «иин», а не «реквизиты», — поэтому теги важнее заголовка.
///
/// Слово засчитывается, если лежит в тексте подстрокой — или если делит начало со словом из
/// текста. Склейка по началу включается с пяти букв: короткие слова вроде «иин» ищутся как
/// есть, иначе «а» находило бы всё. Чепуха по-прежнему не находит ничего — так и надо.
List<HelpArticle> searchHelp(String query) {
  final q = _norm(query.trim());
  if (q.isEmpty) return helpArticles;
  final split = RegExp(r'[^0-9a-zа-я]+');
  final asked = q.split(split).where((w) => w.isNotEmpty).toList();
  final words = asked.where((w) => !_askWords.contains(w)).toList();
  // Спросили одними вопросительными словами — ищем как есть, иначе запрос опустеет и выдаст всё.
  final needles = words.isEmpty ? asked : words;
  return helpArticles.where((a) {
    final hay = _norm([a.title, a.lead, a.where, ...a.steps, ...a.notes, ...a.tags].join(' '));
    final tokens = hay.split(split).where((w) => w.isNotEmpty).toList();
    return needles.every((w) =>
        hay.contains(w) ||
        (w.length >= 5 && tokens.any((t) => t.length >= 4 && _sharedStart(w, t) >= 4)));
  }).toList();
}
