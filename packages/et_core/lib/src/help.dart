  /// То, обо что спотыкаются. Не украшение: каждая строка здесь — чей-то реальный вопрос.
  final List<String> notes;

  /// Слова, которыми это ищут. Человек набирает «иин» или «куда платят», а не «реквизиты».
  final List<String> tags;
}

