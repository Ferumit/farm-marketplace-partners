/// Одна статья. Отвечает на вопрос целиком: что это, где лежит, что нажимать и обо что бьются.
class HelpArticle {
  const HelpArticle({
    required this.id,
    required this.title,
    required this.lead,
    this.where = '',
    this.steps = const [],
    this.notes = const [],
    this.tags = const [],
  });

  /// Совпадает с идентификатором экрана, с которого её открывают значком «?».
  final String id;
  final String title;

  /// Ответ одной фразой. Если человек прочитает только её — он уже знает, что делать.
  final String lead;

  /// Путь до экрана словами: «Профиль → Реквизиты».
